// Builds the SQL printed by scripts/voting-seed.mjs.
//
// Kept as a pure TS function so tests can assert the exact output without
// spawning a process or touching a database. The script itself only reads the
// candidates JSON and writes this string to stdout.

export type VotingSeedCandidate = {
  id: string;
};

/** Quote a value as a SQL text literal, doubling any single quote. */
export function sqlLiteral(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/**
 * Upsert the given ids with their array order as position, then deactivate any
 * candidate that is no longer listed. Re-running produces the same end state.
 */
export function buildVotingSeedSql(
  candidates: readonly VotingSeedCandidate[]
): string {
  const lines: string[] = [
    "-- COMPASS voting candidates seed",
    "-- Generated by scripts/voting-seed.mjs from lib/voting-candidates.json.",
    "-- Safe to re-run: upserts ids/positions and deactivates ids not listed.",
    "-- Run in the Supabase SQL Editor after the voting migrations.",
    "",
  ];

  if (candidates.length === 0) {
    lines.push("-- No candidates in lib/voting-candidates.json.");
    lines.push("update public.voting_candidates");
    lines.push("set active = false;");
    lines.push("");
    return lines.join("\n");
  }

  const ids = candidates.map((candidate) => sqlLiteral(candidate.id));

  lines.push("insert into public.voting_candidates (id, position, active)");
  lines.push("values");
  lines.push(
    candidates
      .map(
        (candidate, index) =>
          `  (${sqlLiteral(candidate.id)}, ${index + 1}, true)`
      )
      .join(",\n")
  );
  lines.push("on conflict (id) do update");
  lines.push("  set position = excluded.position,");
  lines.push("      active = excluded.active;");
  lines.push("");
  lines.push("update public.voting_candidates");
  lines.push("set active = false");
  lines.push("where id not in (");
  lines.push(ids.map((id) => `  ${id}`).join(",\n"));
  lines.push(");");
  lines.push("");

  return lines.join("\n");
}
